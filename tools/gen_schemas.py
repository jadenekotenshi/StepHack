#!/usr/bin/env python3
"""Writes core/schema_data.c from the files in schemas/, so the option lists are compiled into the program.

    python3 tools/gen_schemas.py            # rewrite core/schema_data.c
    python3 tools/gen_schemas.py --check    # exit 1 if it is out of date
"""
import glob
import os
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def c_lines(text):
    out = []
    for line in text.split('\n'):
        if line == '':
            continue
        esc = line.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t')
        out.append('    "%s",' % esc)
    return '\n'.join(out)


def generate():
    names = sorted(glob.glob(os.path.join(root, 'schemas', '*.txt')))
    parts = ['/* Generated by tools/gen_schemas.py from the files in schemas/ -- do not edit. */\n',
             '#include <stdlib.h>\n#include <string.h>\n#include "schema.h"\n',
             '\n/* One string per line (a single literal would pass the 509 characters C89 guarantees). */\n']
    ids = []
    for path in names:
        gid = os.path.splitext(os.path.basename(path))[0]
        ids.append(gid)
        parts.append('static const char *const SCHEMA_%s[] = {\n%s\n    0\n};\n\n' % (gid, c_lines(open(path).read())))
    parts.append('static char *join(const char *const *lines)\n{\n    size_t n = 1;\n    int i;\n    char *s, *p;\n\n')
    parts.append('    for (i = 0; lines[i]; i++) n += strlen(lines[i]) + 1;\n    s = (char *)malloc(n);\n    if (!s) return NULL;\n    p = s;\n')
    parts.append('    for (i = 0; lines[i]; i++) { size_t l = strlen(lines[i]); memcpy(p, lines[i], l); p += l; *p++ = \'\\n\'; }\n    *p = \'\\0\';\n    return s;\n}\n\n')
    parts.append('char *hks_builtin(const char *id)\n{\n')
    for gid in ids:
        parts.append('    if (strcmp(id, "%s") == 0) return join(SCHEMA_%s);\n' % (gid, gid))
    parts.append('    return NULL;\n}\n')
    return ''.join(parts)


def main(argv):
    out = os.path.join(root, 'core', 'schema_data.c')
    text = generate()
    if len(argv) > 1 and argv[1] == '--check':
        cur = open(out).read() if os.path.exists(out) else ''
        if cur != text:
            print('core/schema_data.c is out of date: run python3 tools/gen_schemas.py')
            return 1
        return 0
    open(out, 'w').write(text)
    print('wrote core/schema_data.c')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
